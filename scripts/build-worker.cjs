const { build } = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

async function main() {
  const root = path.join(__dirname, '..');
  const runtime = path.join(root, 'runtime');
  fs.mkdirSync(runtime, { recursive: true });
  const source = path.join(root, 'node_modules/onnxruntime-web/dist');
  for (const filename of fs.readdirSync(source)) {
    if (/^ort-wasm.*\.(mjs|wasm)$/.test(filename)) {
      fs.copyFileSync(path.join(source, filename), path.join(runtime, filename));
    }
  }
  await build({
    absWorkingDir: root, entryPoints: ['src/renderer/transcription.worker.js'],
    outfile: 'src/renderer/transcription.worker.bundle.js',
    bundle: true, platform: 'browser', format: 'esm', target: 'chrome126',
    banner: { js: '// Generated by npm run build:worker. Edit transcription.worker.js instead.' },
    logLevel: 'info',
  });
}
main().catch(error => { console.error(error); process.exitCode = 1; });
